
first_number = int(input("Enter the first number: "))
second_number = int(input("Enter the second number: "))

print("The sum of" + str(first_number) + " and " + str(second_number) + " is: " + str(first_number + second_number))
print("The difference of" + str(first_number) + " and " + str(second_number) + " is: " + str(first_number - second_number))
print("The product of" + str(first_number) + " and " + str(second_number) + " is: " + str(first_number * second_number))
print("The division of" + str(first_number) + " and " + str(second_number) + " is: " + str(first_number / second_number))
